    val enabled: Boolean = false,
    val mode: EnhancementMode = EnhancementMode.HI_RES_FEEL,
    val status: EnhancementStatus = EnhancementStatus.DISABLED,
    val provider: AiProviderType = AiProviderType.GOOGLE_GEMINI,
    val activeProfile: EnhancementProfile = EnhancementProfile.DEFAULT_SAFE,
    val latestCharacteristics: AudioCharacteristics? = null,
    val currentTrackTitle: String = "",
    val isApiKeyConfigured: Boolean = false,
    val statusMessage: String = "Enhancement disabled",
)
