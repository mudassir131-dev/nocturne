package com.mudassir131.yt.playback.enhancement.model

import androidx.annotation.FloatRange
import kotlin.math.max
import kotlin.math.min

/**
 * Compact numerical audio characteristics extracted locally from PCM audio.
 * Sent to the AI optimizer instead of raw audio.
 */
data class AudioCharacteristics(
    val rmsDb: Float = -24.0f,
    val peakDb: Float = -1.0f,
    val crestFactorDb: Float = 12.0f,
    val dynamicRangeDb: Float = 20.0f,
    val spectralCentroidHz: Float = 2500.0f,
    val spectralRolloffHz: Float = 12000.0f,
    val spectralFlux: Float = 0.5f,
    val subBassEnergy: Float = 0.15f,     // 20-60 Hz
    val bassEnergy: Float = 0.25f,        // 60-250 Hz
    val lowMidEnergy: Float = 0.20f,      // 250-500 Hz
    val midEnergy: Float = 0.20f,         // 500-2000 Hz
    val presenceEnergy: Float = 0.12f,    // 2000-6000 Hz
    val highEnergy: Float = 0.08f,        // 6000-20000 Hz
    val airEnergy: Float = 0.03f,         // 10000-20000 Hz
    val estimatedClipping: Float = 0.0f,  // 0.0 (clean) to 1.0 (heavily clipped)
    val estimatedCompression: Float = 0.5f,// 0.0 (very dynamic) to 1.0 (over-compressed/brickwalled)
    val transientDensity: Float = 2.5f,   // Transients / second
    val sampleRate: Int = 44100,
    val channelCount: Int = 2,
)

